char Game_Start(void)
{
    AppContext_SetName((void *)0x536144);
    AppContext_SetQvmOnly(1);
    Modules_Open();
    Flow_New(NULL);
    Flow_SetRequest(AppContext_GetPlayIntro() ? 2 : 4);
    return 1;
}
