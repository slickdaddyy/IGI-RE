# Writes src/exe/data.c: IGI.exe's initialised data for the standalone exe, which lays it out
# at the original addresses. usage: gendata.py IGI.exe > src/exe/data.c
import sys
import pefile

pe = pefile.PE(sys.argv[1])
img = pe.get_memory_mapped_image()
B = pe.OPTIONAL_HEADER.ImageBase
assert B == 0x400000 and pe.FILE_HEADER.TimeDateStamp == 0x3A1D74C6, 'needs the EU IGI.exe'

blocks = []
for s in pe.sections:
    name = s.Name.rstrip(b'\0').decode()
    if name in ('.rdata', '.data'):
        n = min(s.SizeOfRawData, s.Misc_VirtualSize)
        blocks.append((name[1:], B + s.VirtualAddress, n))
# data that dinput.lib left in .text: the mouse and keyboard object formats
blocks += [('dimouse', 0x4AE680, 0xB0), ('dikeyboard', 0x4AE740, 0x1000)]

print('/* IGI.exe\'s initialised data, laid out at its original addresses by main.c.')
print('   Generated by tools/gendata.py from the EU IGI.exe; do not edit. */')
print('#include <stdint.h>\n')
print('const struct IgiData {\n    uint32_t addr, size;\n    const uint8_t *bytes;\n} igi_data[];')
print('const unsigned igi_data_count;')
print('/* where its import descriptors are */')
imp = pe.OPTIONAL_HEADER.DATA_DIRECTORY[1].VirtualAddress
print(f'const uint32_t igi_imports = 0x{B + imp:X};\n')
for name, addr, n in blocks:
    b = img[addr - B:addr - B + n].rstrip(b'\0')  # memory is zeroed anyway
    print(f'static const uint8_t {name}[0x{len(b):X}] = {{')
    for i in range(0, len(b), 16):
        print('    ' + ', '.join(f'0x{x:02X}' for x in b[i:i + 16]) + ',')
    print('};\n')
print('const struct IgiData igi_data[] = {')
for name, addr, n in blocks:
    print(f'    {{0x{addr:X}, sizeof({name}), {name}}},')
print('};\nconst unsigned igi_data_count = sizeof(igi_data) / sizeof(igi_data[0]);')
